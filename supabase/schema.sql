            CREATE TABLE IF NOT EXISTS logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, waktu TEXT, jenis TEXT, pesan TEXT);
            CREATE TABLE IF NOT EXISTS attempts(key TEXT PRIMARY KEY, count INTEGER, until DOUBLE PRECISION);
            CREATE TABLE IF NOT EXISTS outbox(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, token TEXT NOT NULL, kind TEXT NOT NULL, status TEXT NOT NULL, error TEXT DEFAULT '', provider_id TEXT DEFAULT '', updated DOUBLE PRECISION NOT NULL, UNIQUE(token,kind));

